/// 命中即视为敏感字段（输入内容打码）
bool isSecretField(String name) {
  return RegExp(
    r'(password|passwd|pwd|secret|token|cookie|credential|private_key|api_key|sign_key|credit_key|access_key$)',
    caseSensitive: false,
  ).hasMatch(name);
}
